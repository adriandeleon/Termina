    /**
     * A shell prompt, for anything with no mark of its own.
     *
     * <p>Hand-drawn rather than borrowed: it stands for Command Prompt, both PowerShells, sh, ksh
     * and every profile someone writes themselves, so it has to mean "a shell" and not any
     * particular one.
     */
    private static final String PROMPT =
            "M4.4 6.2 L6.5 4.1 L14.4 12 L6.5 19.9 L4.4 17.8 L10.2 12 Z" + " M12.4 17.4 H20.6 V20.4 H12.4 Z";

    /**
     * Which mark a profile gets. Pure, and tested on its own: the decision is a set of name rules,
     * and the node it produces cannot be asserted about without a toolkit.
     *
     * @return a key into {@link #path}, never null
     */
    static String iconKeyFor(Profile profile) {
        if (profile == null) return "prompt";
        String name = profile.name().toLowerCase(Locale.ROOT);
        // The argv, not the rendered command line: a path with a space in it comes back from
        // commandLine() wrapped in quotes, and splitting that on whitespace yields `"c:\program`.
        // Git Bash is exactly that path, so the one Windows shell with a mark of its own lost it.
        String executable = profile.command().isEmpty()
                ? ""
                : fileName(profile.command().get(0).toLowerCase(Locale.ROOT));

        // A WSL entry names a distribution, and the distribution is what there is a mark for — the
        // executable is wsl.exe for every one of them, so it cannot tell them apart.
        if (executable.equals("wsl")) {
            String distro = distroKey(name);
            return distro != null ? distro : "linux";
        }
        // A distribution name in a profile someone wrote by hand — an ssh into a box, say.
        String distro = distroKey(name);
        if (distro != null) return distro;

        return switch (executable) {
            case "bash" -> "bash";
            case "zsh" -> "zsh";
            case "fish" -> "fish";
            default -> "prompt";
        };
    }

    private static String distroKey(String name) {
        if (name.contains("ubuntu")) return "ubuntu";
        if (name.contains("debian")) return "debian";
        if (name.contains("arch")) return "arch";
        if (name.contains("fedora")) return "fedora";
        if (name.contains("alpine")) return "alpine";
        if (name.contains("suse")) return "opensuse";
        if (name.contains("kali")) return "kali";
        return null;
    }

    /**
     * The program a path names, without its directory or its {@code .exe}.
     *
     * <p>The executable rather than anywhere in the line, or {@code sh -c "bash --version"} and a
     * directory called {@code /home/zsh/bin} would both claim a mark they have nothing to do with.
     * Both separators, because a Windows path reaches this on the machine the feature is for.
     */
    private static String fileName(String path) {
        int slash = Math.max(path.lastIndexOf('/'), path.lastIndexOf('\\'));
        String file = slash < 0 ? path : path.substring(slash + 1);
        return file.endsWith(".exe") ? file.substring(0, file.length() - 4) : file;
    }

    private static String path(String key) {
        return switch (key) {
            case "bash" -> BASH;
            case "zsh" -> ZSH;
            case "fish" -> FISH;
            case "ubuntu" -> UBUNTU;
            case "debian" -> DEBIAN;
            case "arch" -> ARCH;
            case "fedora" -> FEDORA;
            case "alpine" -> ALPINE;
            case "opensuse" -> OPENSUSE;
            case "kali" -> KALI;
            case "linux" -> LINUX;
            default -> PROMPT;
        };
    }

